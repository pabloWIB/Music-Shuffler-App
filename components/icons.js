/**
 * Inline SVG icons. Six glyphs do not justify an icon dependency, and shipping
 * them as components keeps them tree-shaken and recolourable via currentColor.
 */

function Icon({ size = 24, strokeWidth = 2, children, ...rest }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...rest}
    >
      {children}
    </svg>
  );
}

